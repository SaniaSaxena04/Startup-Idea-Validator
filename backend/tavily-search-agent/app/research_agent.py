from datetime import datetime, timezone

from app.query_generator import generate_search_queries
from app.tavily_search import (
    create_tavily_client,
    search_web
)


def run_market_research(idea):

    # Create the Tavily client
    client = create_tavily_client()

    # Generate search queries from the startup idea
    queries = generate_search_queries(idea)

    # Store the research results category-wise
    research = {}

    # Store errors if any individual search fails
    errors = []

    # Execute searches for all categories
    for category, query in queries.items():

        try:

            # Perform the web search
            results = search_web(query, client)

            # Store results under their respective category
            research[category] = results

        except Exception as error:

            # If one search fails, continue with the remaining searches
            research[category] = []

            errors.append({
                "category": category,
                "message": str(error)
            })

    # Collect unique source URLs from all categories
    sources_by_url = {}

    for category_results in research.values():

        for result in category_results:

            url = result.get("url")

            # Avoid storing the same URL multiple times
            if url and url not in sources_by_url:

                sources_by_url[url] = {
                    "title": result.get("title", ""),
                    "url": url
                }

    # Prepare the final structured research output
    output = {

        "idea_name": idea.idea_name,

        "target_market": idea.target_market,

        # Record when the research was performed
        "searched_at": datetime.now(timezone.utc).isoformat(),

        # Include the queries generated by the agent
        "search_queries": queries,

        # Include categorized research results
        "research": research,

        # Include unique source URLs
        "sources": list(sources_by_url.values()),

        # Include any search errors
        "errors": errors,

        # Explain the limitations of search results
        "note": (
            "Search results are research evidence and "
            "not a verified market-size estimate or "
            "a final startup-success score."
        )
    }

    return output